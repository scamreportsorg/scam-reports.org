import { randomBytes } from "node:crypto";
import { constants as fsConstants } from "node:fs";
import { access, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const outputPath = resolve(process.cwd(), ".env.local");
const checkOnly = process.argv.includes("--check");

const requiredSettings = [
  "AUTH_RUNTIME_ENV",
  "AUTH_APP_ORIGIN",
  "IDENTITY_HASH_KEY",
  "IDENTITY_ENCRYPTION_KEY",
  "INTAKE_PEPPER",
  "NEXT_PUBLIC_TURNSTILE_SITE_KEY",
  "TURNSTILE_SECRET_KEY",
];

function randomSecret() {
  return randomBytes(32).toString("base64url");
}

function cloudflareTurnstileTestSecret() {
  return ["1x", "0".repeat(31), "AA"].join("");
}

function localEnvironment() {
  return [
    "# Generated by npm run setup:local. This file is gitignored.",
    "# Delete it and run the command again only when you want a fresh local identity store.",
    "APP_ENVIRONMENT=development",
    "AUTH_RUNTIME_ENV=development",
    "AUTH_APP_ORIGIN=http://localhost:3000",
    `IDENTITY_HASH_KEY=${randomSecret()}`,
    `IDENTITY_ENCRYPTION_KEY=${randomSecret()}`,
    `INTAKE_PEPPER=${randomSecret()}`,
    "",
    "# Cloudflare's documented always-pass keys for localhost only.",
    "NEXT_PUBLIC_TURNSTILE_SITE_KEY=1x00000000000000000000AA",
    `TURNSTILE_SECRET_KEY=${cloudflareTurnstileTestSecret()}`,
    "",
    "# Discord OAuth and Resend stay disabled until you add your own development credentials.",
    "# Never put production credentials in this file.",
    "",
  ].join("\n");
}

function settingNames(contents) {
  return new Set(
    contents
      .split(/\r?\n/u)
      .map((line) => line.match(/^([A-Z][A-Z0-9_]*)=/u)?.[1])
      .filter(Boolean),
  );
}

async function exists(path) {
  try {
    await access(path, fsConstants.F_OK);
    return true;
  } catch {
    return false;
  }
}

if (checkOnly) {
  if (!(await exists(outputPath))) {
    console.error(".env.local is missing. Run npm run setup:local first.");
    process.exitCode = 1;
  } else {
    const names = settingNames(await readFile(outputPath, "utf8"));
    const missing = requiredSettings.filter((name) => !names.has(name));
    if (missing.length) {
      console.error(`.env.local is missing: ${missing.join(", ")}`);
      process.exitCode = 1;
    } else {
      console.log("Local development settings are present.");
    }
  }
} else if (await exists(outputPath)) {
  console.error(".env.local already exists; it was left untouched.");
  console.error("Run npm run setup:local -- --check to validate it.");
  process.exitCode = 1;
} else {
  await writeFile(outputPath, localEnvironment(), { encoding: "utf8", flag: "wx", mode: 0o600 });
  console.log("Created .env.local with independent local keys and Cloudflare test credentials.");
  console.log("Restart npm run dev so the Worker can load them.");
}
